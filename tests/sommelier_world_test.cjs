const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert/strict');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const atlas=read('app.js'),index=read('index.html');
const sourceRecipes=JSON.parse(read('data/shakerrr-recipes.json'));
const extra=JSON.parse(read('data/world-spicy-pomegranate.json'));
