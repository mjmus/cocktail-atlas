const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.join(__dirname,'..');
const file=fs.readFileSync(path.join(root,'recipe-measurements.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const custom=fs.readFileSync(path.join(root,'my-recipes-ui.js'),'utf8');
new Function(file);
assert.ok(html.indexOf('recipe-measurements.js')<html.indexOf('my-recipes-ui.js'),'Volume formatter must load before custom recipes');
assert.ok(html.indexOf('recipe-measurements.js')<html.indexOf('app.js'),'Volume formatter must load before app');
assert.ok(app.includes('scaleAmount(x.amount,state.qty,x)'),'Main ingredient display must scale source volume directly');
assert.ok(app.includes("formatGrams(i,state.qty)+' g'+(oz?"),'Copy should include both gram and volume data');
assert.ok(custom.includes('E.scaleAmount(i.amount,servings,i)'),'My Recipes must retain ingredient role when converting');
const context={window:{}};
vm.createContext(context);
vm.runInContext(file,context);
const m=context.window.RecipeMeasurements;
const val=(amount,qty=1,name='Campari',role='add')=>m.measuredAmount({amount,name,role},qty);
assert.equal(val('1 tsp'),'⅙ oz');
assert.equal(val('1 teaspoon'),'⅙ oz');
assert.equal(val('2 teaspoons'),'⅓ oz');
assert.equal(val('3 tsp'),'½ oz');
assert.equal(val('1 tbsp'),'½ oz');
assert.equal(val('1 tablespoon'),'½ oz');
assert.equal(val('2 tbsp'),'1 oz');
assert.equal(val('½ tbsp'),'¼ oz');
assert.equal(val('½ tsp'),'1/12 oz');
assert.equal(val('¼ tsp'),'1/24 oz');
assert.equal(val('⅛ tsp'),'1/48 oz');
assert.equal(val('1 tsp',2),'⅓ oz');
assert.equal(val('1 tsp',3),'½ oz');
assert.equal(val('1 tsp',6),'1 oz');
assert.equal(val('1 tbsp',2),'1 oz');
assert.equal(val('1.5 oz',2),'3 oz');
assert.equal(val('¾ oz',2),'1½ oz');
assert.equal(val('0.75 oz',1),'¾ oz');
assert.equal(val('.5 oz.',1),'½ oz');
assert.equal(val('5 ml'),'0.17 oz');
assert.equal(val('1 tbsp','2')==='1 oz',true);
assert.equal(val('1 tsp',1,'Salt'),'1 tsp','Dry ingredient should retain spoon measure');
assert.equal(val('1 tbsp',1,'Ground cinnamon'),'1 tbsp','Dry spices are not fluid measures');
